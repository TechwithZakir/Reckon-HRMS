  function icon(name) {
    var paths = ICON_PATHS[name] || ICON_PATHS.circle;
    return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' + paths + '</svg>';
  }

  function esc(text) {
    var d = document.createElement("div");
    d.textContent = text;
    return d.innerHTML;
  }

  function render(groups, nav) {
    var here = window.location.pathname.replace(/\/$/, "");
    var html = '<div class="brand">Reckon HRMS</div>';
    groups.forEach(function (g) {
      html += '<div class="group">' + esc(g.label) + '</div>';
      g.items.forEach(function (item) {
        var active = item.url.replace(/\/$/, "") === here ? ' class="active"' : "";
        html += '<a href="' + esc(item.url) + '"' + active + '>' + icon(item.icon) + '<span>' + esc(item.label) + '</span></a>';
      });
    });
    nav.innerHTML = html;
  }

  function init() {
    var nav = document.getElementById("hrms-nav");
    if (!nav) return;
    var toggle = document.getElementById("hrms-toggle");
    if (toggle) toggle.addEventListener("click", function () { nav.classList.toggle("open"); });
    fetch("/api/method/reckon_hrms.api.nav.get_menu", { credentials: "same-origin", headers: { "X-Requested-With": "XMLHttpRequest" } })
      .then(function (r) { return r.json(); })
      .then(function (body) { render(body.message.groups, nav); })
      .catch(function () { nav.textContent = "Menu unavailable."; });
  }

  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init);
  else init();
